// HTTP 状态码中文简注（Worker 与前端共用）。任何地方出现状态码都写成「408 请求超时」这种形式。
export const STATUS_TEXT: Record<number, string> = {
  200: "成功",
  201: "已创建",
  204: "无内容",
  301: "永久重定向",
  302: "临时重定向",
  304: "未修改",
  400: "请求有误",
  401: "未登录",
  403: "禁止访问",
  404: "不存在",
  405: "不支持该方法",
  408: "请求超时",
  409: "冲突",
  410: "已失效",
  413: "内容太大",
  415: "不支持的类型",
  422: "无法处理",
  429: "请求太频繁",
  451: "因法律原因不可用",
  500: "服务器内部错误",
  502: "网关错误",
  503: "服务暂不可用",
  504: "网关超时",
  520: "源站未知错误",
  521: "源站拒绝连接",
  522: "源站连接超时",
  523: "源站不可达",
  524: "源站响应超时",
  525: "源站 SSL 握手失败",
  526: "源站证书无效",
};

/** 「403 禁止访问」；未收录的码按大类兜底。 */
export function statusLabel(code: number): string {
  if (STATUS_TEXT[code]) return `${code} ${STATUS_TEXT[code]}`;
  if (code >= 200 && code < 300) return `${code} 成功`;
  if (code >= 300 && code < 400) return `${code} 重定向`;
  if (code >= 400 && code < 500) return `${code} 客户端错误`;
  if (code >= 500 && code < 600) return `${code} 服务器错误`;
  return String(code);
}
